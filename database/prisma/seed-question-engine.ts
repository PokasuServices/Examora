/**
 * Phase 3 sample data (question engine): a "Rotation Practice" topic quiz in
 * NID UG | UCEED › Visual Spatial Ability › Rotation that uses every new
 * question feature — a question image, image-only options, a multi-select
 * with partial marks, numeric answers (exact and a range), per-question
 * negative marks, and explanations with images and further-reading links.
 *
 * The figures are generated PNGs (seed-images.ts) uploaded to MinIO under
 * study-media/sample/ and registered as CLEAN media. If storage is not
 * reachable, the image questions are skipped and the rest still seeds.
 */
import { PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import type { Prisma, PrismaClient } from "../generated/client/index.js";
import { FIGURE_P, mirror, patternPng, rotate90, type Pattern } from "./seed-images.js";
import { deterministicUuid } from "./seed-id.js";

const sid = (label: string) => deterministicUuid("examora-student-module-seed", label);
const QUIZ_KEY = "rotation-practice";

async function uploadPng(key: string, body: Buffer): Promise<boolean> {
  const client = new S3Client({
    endpoint: process.env.S3_ENDPOINT ?? "http://localhost:9000",
    region: process.env.S3_REGION ?? "us-east-1",
    forcePathStyle: (process.env.S3_FORCE_PATH_STYLE ?? "true") === "true",
    credentials: {
      accessKeyId: process.env.S3_ACCESS_KEY_ID ?? "",
      secretAccessKey: process.env.S3_SECRET_ACCESS_KEY ?? "",
    },
  });
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 3000);
  try {
    await client.send(
      new PutObjectCommand({
        Bucket: process.env.S3_BUCKET ?? "examora-uploads",
        Key: key,
        Body: body,
        ContentType: "image/png",
      }),
      { abortSignal: controller.signal },
    );
    return true;
  } catch {
    return false;
  } finally {
    clearTimeout(timeout);
    client.destroy();
  }
}

/** Uploads each figure once and returns its "media:<id>" ref (null if storage is unavailable). */
async function seedFigures(
  prisma: PrismaClient,
  adminId: string,
): Promise<Record<string, string | null>> {
  const figures: Record<string, { pattern: Pattern; alt: string }> = {
    p: { pattern: FIGURE_P, alt: "Figure P" },
    rot90: { pattern: rotate90(FIGURE_P), alt: "Figure P rotated 90° clockwise" },
    rot180: { pattern: rotate90(rotate90(FIGURE_P)), alt: "Figure P rotated 180°" },
    mirror: { pattern: mirror(FIGURE_P), alt: "Mirror image of figure P" },
    mirrorRot: { pattern: rotate90(mirror(FIGURE_P)), alt: "Mirror image of P, rotated" },
  };
  const refs: Record<string, string | null> = {};
  for (const [name, { pattern, alt }] of Object.entries(figures)) {
    const id = sid(`media:rotation/${name}`);
    let asset = await prisma.cmsAsset.findUnique({ where: { id }, select: { id: true } });
    if (!asset) {
      const key = `study-media/sample/rotation-${name}.png`;
      const png = patternPng(pattern);
      if (await uploadPng(key, png)) {
        asset = await prisma.cmsAsset.create({
          data: {
            id,
            storageKey: key,
            fileName: `rotation-${name}.png`,
            mimeType: "image/png",
            sizeBytes: png.length,
            altText: alt,
            uploadedById: adminId,
            // Generated by the seed itself, so there is nothing to scan.
            scanStatus: "CLEAN",
          },
          select: { id: true },
        });
      }
    }
    refs[name] = asset ? `media:${asset.id}` : null;
  }
  return refs;
}

interface SampleOption {
  text: string;
  image?: string | null;
  correct: boolean;
}
interface SampleQuestion {
  type: "SINGLE_CHOICE" | "MULTIPLE_CHOICE" | "NUMERIC";
  text: string;
  image?: string | null;
  options?: SampleOption[];
  numeric?: [number, number];
  partialMarking?: boolean;
  marks: number;
  negativeMarks?: number;
  explanation: string;
  explanationImage?: string | null;
  resources?: { label: string; url: string }[];
}

function buildQuestions(img: Record<string, string | null>): SampleQuestion[] {
  const imageQuestions: SampleQuestion[] = img.p
    ? [
        {
          type: "SINGLE_CHOICE",
          text: "Which option shows figure P rotated 90° clockwise?",
          image: img.p,
          options: [
            { text: "", image: img.mirror, correct: false },
            { text: "", image: img.rot90, correct: true },
            { text: "", image: img.mirrorRot, correct: false },
            { text: "", image: img.rot180, correct: false },
          ],
          marks: 1,
          negativeMarks: 0.25,
          explanation:
            "Turn the figure a quarter turn clockwise: its **top row becomes the right-hand column**. Options 1 and 3 are mirror images, which no rotation can produce.",
          resources: [
            { label: "Mental rotation", url: "https://en.wikipedia.org/wiki/Mental_rotation" },
          ],
        },
        {
          type: "MULTIPLE_CHOICE",
          text: "Which of these are rotations of figure P? Select all that apply.",
          image: img.p,
          options: [
            { text: "", image: img.rot90, correct: true },
            { text: "", image: img.mirror, correct: false },
            { text: "", image: img.rot180, correct: true },
            { text: "", image: img.mirrorRot, correct: false },
          ],
          partialMarking: true,
          marks: 2,
          explanation:
            "Options 1 and 3 are rotations (90° and 180°). Picking only one of them earns half the marks; picking a mirror image earns none.",
        },
      ]
    : [];

  return [
    ...imageQuestions,
    {
      type: "NUMERIC",
      text: "A circle has a radius of 7 units. Using π = 22/7, what is its area in square units?",
      numeric: [154, 154],
      marks: 1,
      explanation: "Area = πr² = 22/7 × 7 × 7 = **154** square units.",
    },
    {
      type: "NUMERIC",
      text: "The two shorter sides of a right-angled triangle are 3 cm and 4 cm. How long is the longest side, in cm?",
      numeric: [4.95, 5.05],
      marks: 1,
      explanation:
        "By Pythagoras, √(3² + 4²) = √25 = **5 cm**. Any answer from 4.95 to 5.05 is accepted.",
    },
    {
      type: "SINGLE_CHOICE",
      text: "Rotating a figure 90° clockwise twice gives the same result as…",
      options: [
        { text: "Rotating it 180°", correct: true },
        { text: "Mirroring it left to right", correct: false },
        { text: "Rotating it 90° anticlockwise", correct: false },
        { text: "Leaving it unchanged", correct: false },
      ],
      marks: 1,
      negativeMarks: 0.25,
      explanation: "Two quarter turns make a half turn. Figure P after a 180° rotation:",
      explanationImage: img.rot180,
    },
  ];
}

export async function seedRotationQuiz(prisma: PrismaClient, adminId: string): Promise<string> {
  const quizId = sid(`quiz:${QUIZ_KEY}`);
  if (await prisma.quiz.findUnique({ where: { id: quizId }, select: { id: true } })) {
    return "Rotation Practice quiz already present";
  }
  const subjectId = sid("subject:visual-spatial");
  const topicId = sid("topic:visual-spatial/rotation");
  if (!(await prisma.topic.findUnique({ where: { id: topicId }, select: { id: true } }))) {
    return "skipped Rotation Practice quiz (sample course missing)";
  }

  const figures = await seedFigures(prisma, adminId);
  const questions = buildQuestions(figures);

  const assignments: Prisma.QuizQuestionCreateManyInput[] = [];
  for (const [i, q] of questions.entries()) {
    const questionId = sid(`question:${QUIZ_KEY}/${i}`);
    await prisma.question.create({
      data: {
        id: questionId,
        subjectId,
        type: q.type,
        difficulty: "MEDIUM",
        text: q.text,
        imageUrl: q.image ?? null,
        numericMin: q.numeric?.[0] ?? null,
        numericMax: q.numeric?.[1] ?? null,
        partialMarking: q.partialMarking ?? false,
        explanation: q.explanation,
        explanationImageUrl: q.explanationImage ?? null,
        resources: (q.resources ?? []) as unknown as Prisma.InputJsonValue,
        tags: ["rotation"],
        status: "PUBLISHED",
        position: i,
        createdById: adminId,
        options: {
          create: (q.options ?? []).map((o, j) => ({
            id: sid(`option:${QUIZ_KEY}/${i}/${j}`),
            text: o.text,
            imageUrl: o.image ?? null,
            isCorrect: o.correct,
            position: j,
          })),
        },
      },
    });
    assignments.push({
      id: sid(`quiz-question:${QUIZ_KEY}/${i}`),
      quizId,
      questionId,
      marks: q.marks,
      negativeMarks: q.negativeMarks ?? null,
      position: i,
    });
  }

  await prisma.quiz.create({
    data: {
      id: quizId,
      subjectId,
      topicId,
      title: "Rotation Practice",
      slug: `nid-${QUIZ_KEY}`,
      description: "Image questions, partial marks and numeric answers.",
      maxAttempts: 3,
      xpReward: 30,
      level: "MEDIUM",
      status: "PUBLISHED",
      publishedAt: new Date(),
      createdById: adminId,
    },
  });
  await prisma.quizQuestion.createMany({ data: assignments });
  return figures.p
    ? `Rotation Practice quiz with ${questions.length} questions (image figures uploaded)`
    : `Rotation Practice quiz with ${questions.length} questions (storage unavailable, image questions skipped)`;
}
